//! How sparks of each kind glow: their colors as they age, brightness,
//! light cast and how they fly.

use super::*;

impl GlowStyle {
    /// Its color `age` of the way (0 fresh .. 1 spent) through its life.
    pub(in crate::world) fn color(&self, age: f32) -> [f32; 3] {
        let t = age.clamp(0.0, 1.0) * 3.0;
        let k = (t.floor() as usize).min(2);
        let f = t - k as f32;
        let (a, b) = (self.ramp[k], self.ramp[k + 1]);
        [0, 1, 2].map(|c| a[c] + (b[c] - a[c]) * f)
    }
}

